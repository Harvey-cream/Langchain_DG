"""
对话最终回答的格式约定（Markdown），引导模型输出结构清晰、便于复制与前端渲染。
与豆包 / DeepSeek 等产品常见风格对齐：摘要、分节、列表、独立代码块。
"""

# 与 ReAct 兼容：作为「用户消息」前缀，由模型在推理与工具调用后仍遵守最终回答形态。
ANSWER_FORMAT_PREFIX = """【回答格式要求】
在回答用户时，请用 Markdown 输出，风格参考主流对话产品（结构清晰、重点突出）：
1. 开头用 **摘要** 或 **核心结论**（1～3 句），便于快速扫读。
2. 正文用 ##、### 分节；**加粗** 关键术语、数字、结论。
3. 步骤用有序列表；并列要点用无序列表。
4. 命令行、脚本、配置、JSON、环境变量、API 路径等一律放在 fenced 代码块中，并注明语言（如 ```bash、```powershell、```json、```python）。
5. 代码块内仅使用半角字符（ASCII），路径与命令保持可一字不差复制执行；不要混用全角括号、引号。
6. 若有多条独立命令，可写在同一 ```bash 块中，每行一条，或分块说明。
7. 风险提示、注意事项用单独小节或引用块（>）标出。
8. 避免在代码块内写自然语言解释；解释放在代码块外。

---

用户问题：
"""


def wrap_user_message_for_agent(user_text: str) -> str:
    """将格式要求与用户问题合并后交给 Agent。"""
    text = (user_text or "").strip()
    if not text:
        return text
    return ANSWER_FORMAT_PREFIX + text
